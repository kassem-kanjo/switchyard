/**
 * Splits a post-mortem report into the pieces the panel lays out: the headline
 * block (card), then sections. The same Markdown is what the CLI writes, where
 * `<details>` blocks fold natively; here they become collapsible rows. Only
 * text is ever taken from the report (tags are stripped, never rendered).
 */

export interface HeadlineCard {
  /** "Incident 00:30-00:52 ..." */
  eyebrow: string;
  /** The plain-language sentences, one per line of the report: the cause first, then the fix. */
  sentences: string[];
  /** Big numbers: value and caption. */
  stats: { value: string; caption: string }[];
  /** "How we know" provenance line. */
  provenance: string;
}

export interface ReportSection {
  title: string;
  teaser: string;
  open: boolean;
  /** Markdown of the body, without the section's own `## ` heading. */
  body: string;
}

export interface SplitReport {
  /** `# Post-mortem: ...` line, without the marker. */
  title: string;
  card: HeadlineCard | null;
  sections: ReportSection[];
}

const strip = (s: string): string => s.replace(/<[^>]*>/g, "").replace(/\*\*|\*/g, "").trim();
const eachLine = (s: string): string[] => s.split(String.fromCharCode(10)).map(strip).filter((l) => l !== "");

const capitalise = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

/** `**6,264** parcel-min of delay` -> value and caption. */
function parseStat(part: string): { value: string; caption: string } | null {
  const m = /^\*\*([^*]+)\*\*\s*(.*)$/.exec(part.trim());
  return m ? { value: m[1]!.trim(), caption: m[2]!.trim() } : null;
}

/** The four paragraphs the engine puts between the title and `## Summary`. */
function parseCard(paras: string[]): HeadlineCard | null {
  if (paras.length < 4) return null;
  const [eyebrow, sentence, statLine, provenance] = paras as [string, string, string, string];
  const stats = statLine.split(" · ").map(parseStat);
  if (stats.some((s) => s === null) || stats.length === 0) return null;
  return {
    eyebrow: strip(eyebrow),
    sentences: eachLine(sentence),
    stats: stats as { value: string; caption: string }[],
    // The card adds its own "How we know" link, so drop the prefix rather than say it twice.
    provenance: capitalise(strip(provenance).replace(/^How we know:\s*/i, "")),
  };
}

/** Split a report. A report with no headline block (no incident, errors) has `card: null` and one open section. */
export function splitReport(md: string): SplitReport {
  const lines = md.replace(/\r\n?/g, "\n").split("\n");
  let title = "";
  const head: string[] = [];
  const sections: ReportSection[] = [];
  let cur: { title: string; teaser: string; open: boolean; body: string[] } | null = null;
  let inDetails = false;
  let plain: { title: string; body: string[] } | null = null; // an undetailed `## ` section (Summary)

  const closePlain = () => {
    if (plain) sections.push({ title: plain.title, teaser: "", open: true, body: plain.body.join("\n").trim() });
    plain = null;
  };

  for (const raw of lines) {
    const line = raw.trimEnd();
    if (inDetails) {
      if (/^<\/details>/.test(line)) {
        if (cur) sections.push({ ...cur, body: cur.body.join("\n").trim() });
        cur = null;
        inDetails = false;
        continue;
      }
      const sum = /^<summary>(.*)<\/summary>$/.exec(line);
      if (sum && cur && cur.title === "") {
        const text = strip(sum[1]!);
        const [t, ...rest] = text.split(" — ");
        cur.title = (t ?? "").trim();
        cur.teaser = rest.join(" — ").trim();
        continue;
      }
      // The section's own heading repeats the row title: drop it.
      if (cur && /^##\s/.test(line) && cur.body.every((b) => b.trim() === "")) continue;
      cur?.body.push(line);
      continue;
    }
    if (/^<details/.test(line)) {
      closePlain();
      cur = { title: "", teaser: "", open: /^<details\s+open/.test(line), body: [] };
      inDetails = true;
      continue;
    }
    const h1 = /^#\s+(.*)$/.exec(line);
    if (h1 && title === "" && sections.length === 0 && !plain) {
      title = h1[1]!;
      continue;
    }
    const h2 = /^##\s+(.*)$/.exec(line);
    if (h2) {
      closePlain();
      plain = { title: h2[1]!, body: [] };
      continue;
    }
    if (plain) plain.body.push(line);
    else head.push(line);
  }
  closePlain();

  const paras = head
    .join("\n")
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p !== "");
  // Headline block = the first four paragraphs; anything after (the "Generated by" line) stays in front of Summary.
  const card = parseCard(paras);
  const extra = card ? paras.slice(4) : paras;
  if (extra.length > 0 && sections.length > 0 && sections[0]!.title === "Summary") {
    sections[0]!.body = `${extra.join("\n\n")}\n\n${sections[0]!.body}`;
  } else if (extra.length > 0) {
    sections.unshift({ title: "Report", teaser: "", open: true, body: extra.join("\n\n") });
  }
  return { title, card, sections };
}
