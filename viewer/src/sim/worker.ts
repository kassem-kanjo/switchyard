/// <reference lib="webworker" />
// Owns the WASM sim. Robot state codes and cell kinds are produced by the
// Rust facade (crates/wasm/src/lib.rs, "Byte codes") and match
// renderer/Renderer.ts; nothing is remapped here.
import type { SimStats, WasmSimApi, WorkerRequest, WorkerResponse } from "./protocol";

interface WasmModule {
  default(): Promise<unknown>;
  WasmSim: { with_preset(name: string): WasmSimApi };
}

let sim: WasmSimApi | null = null;

function post(msg: WorkerResponse, transfer: Transferable[] = []): void {
  (self as unknown as DedicatedWorkerGlobalScope).postMessage(msg, transfer);
}

function stats(s: WasmSimApi): SimStats {
  return JSON.parse(s.stats_json()) as SimStats;
}

async function handle(req: WorkerRequest): Promise<void> {
  if (req.type === "init") {
    // The pkg directory is generated by `npm run build:wasm`; it is absent in
    // a fresh checkout, so the import is untyped and may fail at runtime.
    // @ts-ignore TS2307 when the generated package does not exist yet.
    const mod = (await import("../wasm/pkg/switchyard_wasm.js")) as WasmModule;
    await mod.default();
    sim = mod.WasmSim.with_preset(req.preset);
    const cells = sim.cells();
    post({ type: "layout", width: sim.width(), height: sim.height(), cells }, [cells.buffer]);
    return;
  }
  if (!sim) throw new Error("sim not initialised");
  if (req.type === "step") {
    sim.step(req.n);
    const robotXY = sim.robot_xy();
    const robotState = sim.robot_state();
    post(
      {
        type: "snapshot",
        tick: sim.tick(),
        robotXY,
        robotState,
        stats: stats(sim),
        hash: sim.state_hash_hex(),
      },
      [robotXY.buffer, robotState.buffer],
    );
  } else {
    post({ type: "stats", stats: stats(sim) });
  }
}

// Requests are handled strictly in order.
let chain: Promise<void> = Promise.resolve();
self.onmessage = (e: MessageEvent<WorkerRequest>) => {
  chain = chain
    .then(() => handle(e.data))
    .catch((err: unknown) => {
      post({ type: "error", message: err instanceof Error ? err.message : String(err) });
    });
};
