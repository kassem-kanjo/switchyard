#!/usr/bin/env bash
# Regenerates expected.txt from the current tree. Hash changes must be
# deliberate: explain them in the PR (see docs/DEVELOPMENT.md).
set -euo pipefail
cd "$(dirname "$0")/../.."
cargo build --release -p switchyard-cli
BIN="target/release/switchyard"
EXPECTED="scripts/determinism/expected.txt"
# scenario(path, relative to repo root) ticks seed
CASES=(
  "scenarios/small.toml 2000 1"
  "scenarios/medium.toml 7200 1"
  "scenarios/large.toml 3600 42"
  "scenarios/chaos/two-dead-robots-and-a-jam.toml 7200 1"
)
{
  echo "# <scenario> <ticks> <seed> <state hash>. Generated by update.sh; do not edit by hand."
  for c in "${CASES[@]}"; do
    read -r scenario ticks seed <<<"$c"
    hash=$("$BIN" run --scenario "$scenario" --ticks "$ticks" --seed "$seed" | tr -d '\r' | sed -n 's/^state hash[[:space:]]*//p')
    echo "$scenario $ticks $seed $hash"
  done
} > "$EXPECTED"
cat "$EXPECTED"
